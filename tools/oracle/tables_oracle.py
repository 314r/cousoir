# Writes the tables Cousoir takes from Calibre rather than porting by hand:
#
# - calibre_unidecode.inc: the ASCII replacement of every character of the
#   Basic Multilingual Plane, as ascii_filename() transliterates file and
#   folder names with Unihandecode's default (Chinese and others) table;
# - calibre_strings.inc: Calibre's translations of "Unknown", the title and
#   author of a book without one, and "Cover", the title of an OPF's cover
#   reference; the language of a MOBI file by its header's code; and the
#   named character references replace_entities() knows.
#
#   calibre-debug -e tools/oracle/tables_oracle.py -- <source folder>

import os
import sys

from calibre.constants import __version__
from calibre.ebooks.html_entities import html5_entities
from calibre.ebooks.mobi.langcodes import mobi2iana
from calibre.ebooks.unihandecode.unidecoder import Unidecoder
from calibre.utils.localization import canonicalize_lang, get_all_translators

out = sys.argv[-1]


def c_string(text):
    escaped = text.encode('utf-8').decode('latin-1')
    result = []
    for ch in escaped:
        code = ord(ch)
        if ch in '"\\':
            result.append('\\' + ch)
        elif 32 <= code < 127:
            result.append(ch)
        else:
            result.append('\\%03o' % code)
    return '"' + ''.join(result) + '"'


decoder = Unidecoder()
strings = ['']
positions = {'': 0}
index = []
for code in range(0x80, 0x10000):
    replacement = decoder.replace_point(chr(code))
    if replacement not in positions:
        positions[replacement] = len(strings)
        strings.append(replacement)
    index.append(positions[replacement])

with open(os.path.join(out, 'calibre_unidecode.inc'), 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/oracle/tables_oracle.py from Calibre %s; do not edit.\n' % __version__)
    f.write('// Unihandecode\'s replacement for each character from U+0080 to U+FFFF.\n')
    f.write('''//
// The table is Calibre's Unihandecode, src/calibre/ebooks/unihandecode,
// Copyright (C) 2010-2011 Hiroshi Miura and 2009 John Schember, GPL v3; it
// comes from Text::Unidecode, Copyright (C) 2001 Sean M. Burke, by way of
// Russell Norris's Ruby unidecode, and from the Unicode Consortium's Unihan
// database for the Han characters.

''')
    f.write('static const char *const unidecodeStrings[] = {\n')
    for start in range(0, len(strings), 8):
        f.write('    ' + ', '.join(c_string(s) for s in strings[start:start + 8]) + ',\n')
    f.write('};\n\n')
    f.write('static const unsigned short unidecodeIndex[] = {\n')
    for start in range(0, len(index), 16):
        f.write('    ' + ','.join(str(i) for i in index[start:start + 16]) + ',\n')
    f.write('};\n')

translations = {'en': ('Unknown', 'Cover')}
for lang, translator in get_all_translators():
    translations[lang] = (translator.gettext('Unknown'), translator.gettext('Cover'))

with open(os.path.join(out, 'calibre_strings.inc'), 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/oracle/tables_oracle.py from Calibre %s; do not edit.\n' % __version__)
    f.write('// Calibre\'s translations of "Unknown" and "Cover", by interface language.\n')
    f.write('''//
// From Calibre, https://calibre-ebook.com, GPL v3: the translations are the
// work of Calibre's translators; the MOBI language codes come from
// src/calibre/ebooks/mobi/langcodes.py and the named character references
// from src/calibre/ebooks/html_entities.py, Copyright (C) Kovid Goyal.

''')
    f.write('static const struct { const char *language; const char *unknown; const char *cover; } calibreStrings[] = {\n')
    for lang in sorted(translations):
        unknown, cover = translations[lang]
        f.write('    { %s, %s, %s },\n' % (c_string(lang), c_string(unknown), c_string(cover)))
    f.write('};\n\n')
    f.write('// mobi2iana() of a MOBI header\'s language code, as canonicalize_lang() keeps it.\n')
    f.write('static const struct { int code; const char *language; } mobiLanguages[] = {\n')
    for code in range(256):
        try:
            language = canonicalize_lang(mobi2iana(code, 0))
        except Exception:
            language = None
        if language:
            f.write('    { %d, %s },\n' % (code, c_string(language)))
    f.write('};\n')
    f.write('\n// replace_entities()\'s named references, sorted by name.\n')
    f.write('static const struct { const char *name; const char *value; } htmlEntities[] = {\n')
    for name in sorted(html5_entities):
        f.write('    { %s, %s },\n' % (c_string(name), c_string(html5_entities[name])))
    f.write('};\n')
