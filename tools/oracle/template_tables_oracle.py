# Writes calibre_template.inc, what Calibre's templates read besides the
# books, taken from Calibre rather than ported by hand:
#
# - the built-in fields of FieldMetadata, src/calibre/library/field_metadata.py:
#   each field's key, kind, data type, separator between its values when it
#   holds several, its search terms and, for a date, how it shows;
# - by interface language, the names of the days and months format_date()
#   writes (Calibre's lcdata) and the words templates print: "Yes", "No",
#   "None", "Error", "DRM", "Unknown", "TEMPLATE ERROR" and the text of an
#   unknown function.
#
#   calibre-debug -e tools/oracle/template_tables_oracle.py -- <source folder>

import os
import sys

from calibre.constants import __version__
from calibre.library.field_metadata import FieldMetadata
from calibre.utils.localization import get_all_translators, lcdata as english_lcdata, translator_for_lang

out = sys.argv[-1]


def c_string(text):
    escaped = text.encode('utf-8').decode('latin-1')
    result = []
    for ch in escaped:
        code = ord(ch)
        if ch in '"\\':
            result.append('\\' + ch)
        elif 32 <= code < 127:
            result.append(ch)
        else:
            result.append('\\%03o' % code)
    return '"' + ''.join(result) + '"'


fm = FieldMetadata()
fields = []
for key in fm.all_field_keys():
    meta = fm[key]
    multiple = meta.get('is_multiple') or {}
    fields.append((key, meta.get('kind') or '', meta.get('datatype') or '', multiple.get('list_to_ui') or '',
                   '|'.join(meta.get('search_terms', [])), (meta.get('display') or {}).get('date_format') or ''))
terms = sorted(fm._search_term_map.items())

words = ('Yes', 'No', 'None', 'Error', 'DRM', 'TEMPLATE ERROR', '%s: unknown function', 'Unknown',
         "No book formats found so the path can't be generated", 'No such variable {0}')
languages = {'en': (english_lcdata, tuple(words))}
for lang, translator in get_all_translators():
    data = translator_for_lang(lang)['lcdata'] or english_lcdata
    languages[lang] = (data, tuple(translator.gettext(w) for w in words))

with open(os.path.join(out, 'calibre_template.inc'), 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/oracle/template_tables_oracle.py from Calibre %s; do not edit.\n' % __version__)
    f.write('''// What Calibre's templates read besides the books: the built-in fields and
// their search terms, and by interface language the names of days and months
// and a few words.
//
// From Calibre, https://calibre-ebook.com, GPL v3: the fields come from
// src/calibre/library/field_metadata.py, Copyright (C) Kovid Goyal; the
// names and words are the work of Calibre's translators and of the locale
// data Calibre ships.

''')
    f.write('static const struct { const char *key; const char *kind; const char *datatype; const char *listToUi; '
            'const char *searchTerms; const char *dateFormat; } templateFields[] = {\n')
    for field in fields:
        f.write('    { ' + ', '.join(c_string(x) for x in field) + ' },\n')
    f.write('};\n\n')
    f.write('static const struct { const char *term; const char *key; } templateSearchTerms[] = {\n')
    for term, key in terms:
        f.write('    { %s, %s },\n' % (c_string(term), c_string(key)))
    f.write('};\n\n')
    f.write('static const struct { const char *language; const char *days[7]; const char *abbreviatedDays[7]; '
            'const char *months[12]; const char *abbreviatedMonths[12]; const char *words[%d]; } '
            'templateLanguages[] = {\n' % len(words))
    for lang in sorted(languages):
        data, translated = languages[lang]
        f.write('    { %s,\n' % c_string(lang))
        for key in ('day', 'abday', 'mon', 'abmon'):
            f.write('      { ' + ', '.join(c_string(x) for x in data[key]) + ' },\n')
        f.write('      { ' + ', '.join(c_string(x) for x in translated) + ' } },\n')
    f.write('};\n')
