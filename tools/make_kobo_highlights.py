def spans(kepub, name):
    with zipfile.ZipFile(kepub) as z:
        root = ET.fromstring(z.read('OEBPS/text/' + name))
    return {span.get('id'): span.text or '' for span in root.iter(XHTML + 'span') if span.get('class') == 'koboSpan'}


def quote(value):
    if value is None:
        return 'NULL'
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + value.replace("'", "''") + "'"


def row(*values):
    return '    (' + ', '.join(quote(v) for v in values) + ')'


